class Command(BaseCommand):
    help = 'Seed Tamilnadu pincodes for delivery'

    def handle(self, *args, **options):
        created = 0
        for pincode, city, delivery_type, days, pickup, cod in PINCODES:
            _, was_created = DeliveryPincode.objects.get_or_create(
                pincode=pincode,
                defaults={
                    'city': city,
                    'delivery_type': delivery_type,
                    'estimated_days_text': days,
                    'store_pickup_available': pickup,
                    'cod_available': cod,
                    'is_active': True,
                }
            )
            if was_created:
                created += 1

        self.stdout.write(self.style.SUCCESS(f'Seeded {created} pincodes (total: {DeliveryPincode.objects.count()})'))
